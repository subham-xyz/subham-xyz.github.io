import assert from 'node:assert/strict';
import {searchOutput, validate, checkDimensions, checkFile} from '../src/scripts/image-core.mjs';
import {score, silhouette} from '../src/scripts/font-score.mjs';
const render = async (w, h, q) => new Blob([new Uint8Array(Math.round(w * h * q + 100))], {type:'image/jpeg'});
const base = {width:100, height:100, quality:.8, mime:'image/jpeg'};
const hit = await searchOutput(render, {...base, max:4000});
assert.ok(hit.blob.size <= 4000);
assert.equal(hit.width, 100);
const impossible = await searchOutput(render, {...base, max:50, downscale:true, fixed:true});
assert.equal(impossible.width, 100);
assert.equal(impossible.height, 100);
assert.match(validate(impossible, {max:50})[0], /unreachable/);
const minimum = await searchOutput(render, {...base, min:9000, max:11000});
assert.equal(validate(minimum, {min:9000, max:11000, width:100, height:100, mime:'image/jpeg'}).length, 0);
assert.ok(validate(minimum, {min:20000, max:100, width:20, height:20, mime:'image/png'}).length === 5);
const shrink = await searchOutput(render, {...base, mime:'image/png', max:2000, downscale:true});
assert.ok(shrink.width < 100 && shrink.blob.size <= 2000);
assert.throws(() => checkDimensions(5000, 5000));
assert.throws(() => checkDimensions(NaN, 100));
assert.throws(() => checkFile({name:'photo.heic', size:100}));
assert.throws(() => checkFile({name:'photo.png', size:21 * 1048576}));
const a = {values: Float32Array.of(0,1,1,0), aspect:3};
assert.equal(score(a, a), 0);
assert.ok(score(a, {values:Float32Array.of(1,0,0,1), aspect:3}) > score(a,a));
assert.throws(() => silhouette({width:2,height:2,data:new Uint8ClampedArray(16)}), /silhouette/);
console.log('PASS: target search, impossible targets, exact dimensions, minimum sizes, all constraints, downscaling, file guards and silhouette scoring.');
